comment on table public.chat_customer_evidence is
  'Immutable-ish audit ledger of raw customer Facebook messages, separate from order evidence and Chat UI projections';
comment on column public.chat_customer_evidence.dedupe_key is
  'Stable idempotency key; prefer meta:<source_message_id>'; 
comment on column public.chat_customer_evidence.raw_payload is
  'Original normalized Meta/n8n payload retained for investigation';
